/** Generate the compact site-builder reference. Engineering policy lives in CLAUDE.md. */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { CONFIG_SCHEMA } from "#config/config-schema.js";
import { SITE_SCHEMA } from "#config/site-schema.js";
import { ROOT_DIR } from "#lib/paths.js";
import { COLLECTIONS } from "#scripts/customise-cms/collections.js";
import { FEATURE_QUESTIONS } from "#scripts/customise-cms/feature-questions.js";
import { runIfMain } from "#scripts/lib/is-main-module.js";
import {
  escapeText,
  fencedCode,
  inlineCode,
  markdownTable,
} from "#scripts/lib/markdown.js";
import { renderFieldTable } from "#scripts/lib/render-blocks-reference.js";

/** @typedef {{ engines: { node: string }, scripts: Record<string, string> }} PackageInfo */
/** @typedef {{ packageJson: PackageInfo, collections: typeof COLLECTIONS, features: typeof FEATURE_QUESTIONS, settings: typeof CONFIG_SCHEMA, identity: typeof SITE_SCHEMA }} ReferenceInputs */

const SITE_SCRIPTS = [
  "serve",
  "build",
  "customise-cms",
  "check:links",
  "check:a11y",
  "lint:scss",
  "test",
  "generate-references",
];

/** @param {PackageInfo} packageJson */
const renderSiteCommands = ({ engines, scripts }) =>
  [
    "## Runtime And Commands",
    `Use Node ${inlineCode(engines.node)} and npm. Install dependencies from the repository root:`,
    fencedCode("npm install", "sh"),
    "Selected site-building commands from [package.json](../package.json). See [verification](../skills/cfa-static-site-builder/references/verification.md) for which checks to run.",
    markdownTable(
      ["Command", "Package Script"],
      SITE_SCRIPTS.map((name) => {
        if (!Object.hasOwn(scripts, name))
          throw new Error(`Missing site-builder script: ${name}`);
        return [inlineCode(`npm run ${name}`), inlineCode(scripts[name])];
      }),
    ),
  ].join("\n\n");

/** @param {ReferenceInputs["collections"]} collections @param {ReferenceInputs["features"]} features */
const renderCmsChoices = (collections, features) =>
  [
    "## CMS Choices",
    "These are available editor options, not this site's saved selection. CMS collection choices do not control what Eleventy publishes. See [project setup](../skills/cfa-static-site-builder/references/project-setup.md#choose-collections-and-cms-features) before changing them.",
    markdownTable(
      ["Collection", "Content Directory", "Availability", "Depends On"],
      collections.map((collection) => [
        inlineCode(collection.name),
        inlineCode(collection.path),
        collection.required
          ? "Required"
          : collection.internal
            ? "Internal"
            : "Optional",
        collection.dependencies.length
          ? collection.dependencies.map(inlineCode).join(", ")
          : "None",
      ]),
    ),
    markdownTable(
      ["Feature", "Editor Choice"],
      features.map(([name, question]) => [
        inlineCode(name),
        escapeText(question),
      ]),
    ),
  ].join("\n\n");

/** @param {ReferenceInputs["identity"]} identity */
const renderSiteIdentity = (identity) =>
  [
    "## Site Identity",
    "Every field [site.json](../src/_data/site.json) accepts, from the [site schema](../src/_lib/config/site-schema.js). The build fails on an unknown field, a missing required field, a value of the wrong type, a malformed or placeholder URL, or a placeholder name. Fields with a CMS label are editable in the CMS Site Configuration file.",
    renderFieldTable(identity),
  ].join("\n\n");

/** @param {ReferenceInputs["settings"]} settings */
const renderSiteConfiguration = (settings) =>
  [
    "## Site Configuration",
    "Every setting [config.json](../src/_data/config.json) accepts, from the [config schema](../src/_lib/config/config-schema.js). A site's config.json holds only the settings it changes; an omitted or `null` setting takes its default. The build fails on an unknown setting, a value of the wrong type, or a value outside the listed choices.",
    markdownTable(
      ["Setting", "Type", "Default", "Choices", "Description"],
      Object.entries(settings).map(([key, setting]) => [
        inlineCode(key),
        inlineCode(setting.list ? `array<${setting.type}>` : setting.type),
        inlineCode(JSON.stringify(setting.default)),
        setting.choices ? setting.choices.map(inlineCode).join(", ") : "Any",
        escapeText(setting.description),
      ]),
    ),
  ].join("\n\n");

/** Pure rendering of the package, CMS, and config definitions supplied by the caller.
 * @param {ReferenceInputs} inputs
 */
export const renderDeveloperReference = ({
  packageJson,
  collections,
  features,
  settings,
  identity,
}) =>
  `${[
    "<!-- Generated by scripts/generate-developer-reference.js. DO NOT EDIT. -->",
    "# Site Builder Reference",
    "For creating and maintaining a site with CfA Static. Regenerate with `npm run generate-references`, or `npm run generate-developer-reference` for this file alone.",
    renderSiteCommands(packageJson),
    renderCmsChoices(collections, features),
    renderSiteIdentity(identity),
    renderSiteConfiguration(settings),
    "## Content And Layouts",
    "- [Project setup](../skills/cfa-static-site-builder/references/project-setup.md): site identity, navigation, CMS, languages, and publishing.",
    "- [Content authoring](../skills/cfa-static-site-builder/references/content-authoring.md): pages, news, guides, snippets, and media.",
    "- [Block reference](../skills/cfa-static-site-builder/references/blocks.md): accepted fields and canonical YAML examples.",
    "- [Layouts](../skills/cfa-static-site-builder/references/layouts.md): columns, sidebars, and styling conventions.",
    "## Themes",
    "Edit [theme.scss](../src/css/theme.scss), browse the theme files in [src/css](../src/css/), or preview and export a theme at `/theme-editor/` on the running site.",
    "Consult the [Sass defaults](../src/css/_variables.scss) and [breakpoints](../src/css/_breakpoints.scss) rather than copying their values into another reference. Prefer theme overrides over changes to core styles.",
  ].join("\n\n")}\n`;

/** Read only the package manifest; CMS and config definitions are shared with the build. */
export const readDeveloperReferenceInputs = () => ({
  packageJson: JSON.parse(readFileSync(join(ROOT_DIR, "package.json"), "utf8")),
  collections: COLLECTIONS,
  features: FEATURE_QUESTIONS,
  settings: CONFIG_SCHEMA,
  identity: SITE_SCHEMA,
});

await runIfMain(import.meta.url, () => {
  writeFileSync(
    join(ROOT_DIR, "docs/developer-reference.md"),
    renderDeveloperReference(readDeveloperReferenceInputs()),
  );
  console.log("Generated docs/developer-reference.md");
});
